<?php
/** Opt-in integration on a disposable test database; never uses MODX runtime/config. */
$dsn=getenv('ARCHIVEFILE_TEST_MYSQL_DSN');
if (!$dsn) { fwrite(STDERR,"Set ARCHIVEFILE_TEST_MYSQL_DSN for an isolated test database\n"); exit(2); }
require dirname(__DIR__).'/core/components/archivefile/model/archivefile.class.php';
require __DIR__.'/fixtures/service.php';
$root=sys_get_temp_dir().'/archivefile-mysql-'.bin2hex(random_bytes(6)).'/';mkdir($root,0700);
define('MODX_CORE_PATH',$root);define('MODX_ASSETS_PATH',$root.'assets/');define('MODX_ASSETS_URL','/assets/');
class MysqlModx {
    public $pdo; public $prefix;
    public function __construct($dsn) {
        $this->prefix='af_test_'.bin2hex(random_bytes(6)).'_';
        $this->pdo=new PDO($dsn,getenv('ARCHIVEFILE_TEST_MYSQL_USER')?:'root',getenv('ARCHIVEFILE_TEST_MYSQL_PASSWORD')?:'',array(PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION));
    }
    public function connect(){return true;}
    public function getOption($key,$options=null,$default=null){return array('table_prefix'=>$this->prefix,'archivefile.storage_path'=>MODX_CORE_PATH.'storage/','site_url'=>'https://example.org/','assets_url'=>'/assets/')[$key]??$default;}
    public function log($level,$message){echo $message.PHP_EOL;}
}
$modx=new MysqlModx($dsn);$s=new FixtureService($modx);
function assertMysql($ok,$message){if(!$ok)throw new RuntimeException($message);echo 'PASS MySQL '.$message.PHP_EOL;}
try {
    $s->install();$s->install();
    $indexes=$s->query('SHOW INDEX FROM '.$s->table('events'))->fetchAll(PDO::FETCH_ASSOC);
    assertMysql(count(array_intersect(array('source_status_event','kind_event','status_event'),array_column($indexes,'Key_name')))===3,'idempotent additive indexes');
    $id=$s->save(array('name'=>'MySQL fixture','url'=>'https://example.org/feed.xml','enabled'=>1));
    for($i=0;$i<5;$i++)$s->fetch($id);
    assertMysql(count($s->copies($id))===3 && count($s->sources())===1,'InnoDB fetch, rotation and batched list');
    $before=array_column($s->copies($id),'id');$s->failPublish=true;
    try{$s->fetch($id);throw new RuntimeException('Expected publication failure');}catch(RuntimeException $e){if($e->getMessage()!=='Failure after publishing bytes')throw $e;}
    assertMysql(array_column($s->copies($id),'id')===$before,'publication failure rolls back SQL history');
    $s->delete($id);assertMysql(!$s->sources(),'retryable deletion');
} finally {
    // Table names are generated by this test; no table from a site is read or dropped.
    foreach(array('copies','events','options','sources') as $table)$s->query('DROP TABLE IF EXISTS '.$s->table($table));
    $iterator=new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root,FilesystemIterator::SKIP_DOTS),RecursiveIteratorIterator::CHILD_FIRST);
    foreach($iterator as $path){if($path->isDir())rmdir($path->getPathname());else unlink($path->getPathname());}rmdir($root);
}
